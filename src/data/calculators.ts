export type QuestionType = 'choice' | 'inputs' | 'contact';

export interface SizeInput {
  label: string;       // подпись/placeholder поля
  unit?: string;       // единица измерения (м², м.п. и т.п.)
}

export interface Question {
  /** Заголовок без номера, напр. «Выберите тип крыши» */
  title: string;
  type: QuestionType;
  /** Варианты-«пилюли» для type === 'choice' */
  options?: string[];
  /** Поля ввода для type === 'inputs' */
  inputs?: SizeInput[];
  /** Ссылка-подсказка под полями (type === 'inputs'), напр. «У вас сложный тип кровли?» */
  helpLink?: string;
}

export interface Calculator {
  slug: string;
  title: string;       // H1 и крошки
  navTitle: string;    // короткое имя для крошек/списков
  short: string;       // лид-абзац под заголовком
  unit: string;
  kind: 'krovlya' | 'fasad' | 'vodostok';
  /** Вопросы квиза по порядку. Последний — контактный шаг (type 'contact'). */
  questions: Question[];
}

